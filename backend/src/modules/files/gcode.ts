import { createReadStream, createWriteStream } from 'node:fs';
import { open, rename, rm, stat } from 'node:fs/promises';
import { pipeline } from 'node:stream/promises';
import type { GcodeSummary } from '../../types.js';
import { analyzeGcodeFile, type AnalyzeOptions } from './gcode-analyzer.js';
import { GcodeScanner } from './gcode-scan.js';

async function readRange(path: string, start: number, length: number): Promise<Buffer> {
  const fh = await open(path, 'r');
  try {
    const buf = Buffer.alloc(length);
    const { bytesRead } = await fh.read(buf, 0, length, start);
    return buf.subarray(0, bytesRead);
  } finally {
    await fh.close();
  }
}

const HEAD_BYTES = 256 * 1024;
const TAIL_BYTES = 1024 * 1024;

/** "1d 2h 3m 4s" / "2h 3m" / "45s" → seconds. */
export function parseDuration(s: string): number | null {
  let total = 0;
  let matched = false;
  for (const m of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    matched = true;
    const n = Number(m[1]);
    total += m[2] === 'd' ? n * 86400 : m[2] === 'h' ? n * 3600 : m[2] === 'm' ? n * 60 : n;
  }
  return matched ? Math.round(total) : null;
}

const numList = (s: string) =>
  s
    .split(',')
    .map((v) => Number(v.trim()))
    // Negative entries could push a total down (`= 500,-499`).
    .filter((n) => Number.isFinite(n) && n >= 0);

/** Longest comment line the summary looks at (real ones are < 200 chars; the config block's longest ~2 KB). */
const MAX_LINE = 4096;

/** The comment lines of `text` (`;` first, CR dropped), each cut to MAX_LINE: no regex ever sees a huge line. */
function commentLines(text: string): string[] {
  const out: string[] = [];
  let start = 0;
  while (start < text.length) {
    let end = text.indexOf('\n', start);
    if (end < 0) end = text.length;
    if (text.charCodeAt(start) === 59 /* ; */) {
      let l = text.slice(start, Math.min(end, start + MAX_LINE));
      if (l.endsWith('\r')) l = l.slice(0, -1);
      out.push(l);
    }
    start = end + 1;
  }
  return out;
}

/**
 * Reads the metadata Creality Print / OrcaSlicer / Bambu write into a G-code file: the header line `; generated by`,
 * the footer summary (`; filament used [g] = …`, `; estimated printing time (normal mode) = …`,
 * `; total layers count = …`) and `; printer_model = …` from the config block. Only the head and tail are read.
 */
export function parseGcodeSummaryText(head: string, tail: string): GcodeSummary {
  // Line by line, each line capped: patterns run on one short line at a time, so a crafted file (huge lines,
  // whitespace runs, millions of `;`) costs linear time instead of the quadratic backtracking a whole-text
  // multiline regex allows (`\s` there also crosses newlines).
  const lines = commentLines(`${head}\n${tail}`);
  const line = (re: RegExp) => {
    for (const l of lines) {
      const m = re.exec(l);
      if (m) return m[1]?.trim();
    }
    return undefined;
  };
  const generated = line(/^;[ \t]*generated by[ \t]+(.+?)(?:[ \t]+on[ \t]+\d{4}-\d{2}-\d{2}.*)?$/i);
  // Cura writes "; Generated with Cura_SteamEngine 5.x".
  const slicer: string | null = generated ?? line(/^;[ \t]*Generated with[ \t]+(.+)$/i) ?? null;
  const time =
    line(/^;[ \t]*estimated printing time \(normal mode\)[ \t]*=[ \t]*(.+)$/i) ??
    line(/^;[ \t]*total estimated time:[ \t]*([^;]+)/i) ??
    line(/^;[ \t]*estimated printing time[ \t]*=[ \t]*(.+)$/i);
  let printSeconds = time ? parseDuration(time) : null;
  if (printSeconds === null) {
    const cura = line(/^;TIME:(\d+)/);
    if (cura) printSeconds = Number(cura);
  }
  const grams = line(/^;[ \t]*filament used \[g\][ \t]*=[ \t]*(.+)$/i);
  const mm = line(/^;[ \t]*filament used \[mm\][ \t]*=[ \t]*(.+)$/i);
  const layersRaw = line(/^;[ \t]*total layers count[ \t]*=[ \t]*(\d+)/i) ?? line(/^;[ \t]*total layer number:[ \t]*(\d+)/i) ?? line(/^;LAYER_COUNT:(\d+)/);
  let printerModel = line(/^;[ \t]*printer_model[ \t]*=[ \t]*(.+)$/i) ?? null;
  if (printerModel === '') printerModel = null;
  return {
    printSeconds,
    filamentGrams: grams ? numList(grams) : [],
    filamentMm: mm ? numList(mm) : [],
    layers: layersRaw ? Number(layersRaw) : null,
    printerModel,
    slicer,
  };
}

export async function parseGcodeSummary(path: string): Promise<GcodeSummary> {
  const { size } = await stat(path);
  const head = (await readRange(path, 0, Math.min(size, HEAD_BYTES))).toString('latin1');
  // Files that fit in the head are read once; otherwise the last MB holds the footer and config block.
  const tailStart = Math.max(0, size - TAIL_BYTES);
  const tail = size <= HEAD_BYTES ? '' : (await readRange(path, tailStart, size - tailStart)).toString('latin1');
  return parseGcodeSummaryText(head, tail);
}

/**
 * Summary for G-code PrintYard did not slice (uploads): the comments are only kept as `declared` (display); the
 * numbers used for limits are computed from the moves (`estimateSource: 'computed'`).
 */
export async function computeGcodeSummary(path: string, opts: AnalyzeOptions = {}): Promise<GcodeSummary> {
  const declared = await parseGcodeSummary(path);
  const scanner = new GcodeScanner();
  const a = await analyzeGcodeFile(path, { ...opts, hooks: [...(opts.hooks ?? []), scanner.hook] });
  return {
    printSeconds: a.seconds,
    filamentGrams: a.grams,
    filamentMm: a.mm,
    layers: a.layers,
    printerModel: declared.printerModel,
    slicer: declared.slicer,
    estimateSource: 'computed',
    declared: { printSeconds: declared.printSeconds, filamentGrams: declared.filamentGrams, layers: declared.layers },
    scan: scanner.result(),
  };
}

export interface Thumbnail {
  width: number;
  height: number;
  png: Buffer;
}

/** One `; THUMBNAIL_BLOCK_START … END` block per image, exactly as GCodeThumbnails::export_thumbnails_to_file writes PNG. */
export function thumbnailBlock(thumbs: Thumbnail[]): string {
  let out = '';
  for (const t of thumbs) {
    const b64 = t.png.toString('base64');
    out += '; THUMBNAIL_BLOCK_START\n';
    out += `\n;\n; thumbnail begin ${t.width}x${t.height} ${b64.length}\n`;
    for (let i = 0; i < b64.length; i += 78) out += `; ${b64.slice(i, i + 78)}\n`;
    out += '; thumbnail end\n';
    out += '; THUMBNAIL_BLOCK_END\n\n';
  }
  return out;
}

/** PNG signature + IHDR width/height, or null when not a PNG. */
export function pngSize(buf: Buffer): { width: number; height: number } | null {
  if (buf.length < 24) return null;
  if (buf.readUInt32BE(0) !== 0x89504e47 || buf.readUInt32BE(4) !== 0x0d0a1a0a) return null;
  if (buf.toString('latin1', 12, 16) !== 'IHDR') return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

/**
 * Copies `src` to `dest` with thumbnails inserted after `; HEADER_BLOCK_END` (where the GUI writes them).
 * The engine's `; EXCLUDE_OBJECT_ID … END_OFFSET=<byte>` footer holds byte offsets into the file, so they are shifted
 * by the inserted length. Streams the body; only the head and the last MB are held in memory.
 */
export async function injectThumbnails(src: string, dest: string, thumbs: Thumbnail[]): Promise<void> {
  const tmp = `${dest}.${process.pid}.thumb.part`;
  try {
    const { size } = await stat(src);
    const headBuf = await readRange(src, 0, Math.min(size, HEAD_BYTES));
    const head = headBuf.toString('latin1');
    // Insert after the header block and its blank line; files without one get the thumbnails at the top.
    const m = /; HEADER_BLOCK_END\r?\n(\r?\n)?/.exec(head);
    const insertAt = m ? m.index + m[0].length : 0;
    const block = Buffer.from(thumbnailBlock(thumbs), 'latin1');
    const delta = block.length;
    const tailStart = Math.max(insertAt, size - TAIL_BYTES);
    const out = createWriteStream(tmp);
    const write = (b: Buffer) =>
      new Promise<void>((resolve, reject) => out.write(b, (err) => (err ? reject(err) : resolve())));
    await write(headBuf.subarray(0, insertAt));
    await write(block);
    if (tailStart > insertAt) {
      await pipeline(createReadStream(src, { start: insertAt, end: tailStart - 1 }), out, { end: false });
    }
    const tail = (await readRange(src, tailStart, size - tailStart)).toString('latin1');
    const fixed = tail.replace(/(; EXCLUDE_OBJECT_ID\b[^\n]*?END_OFFSET=)(\d+)/g, (_all, pre: string, n: string) => `${pre}${Number(n) + delta}`);
    await write(Buffer.from(fixed, 'latin1'));
    await new Promise<void>((resolve, reject) => {
      out.on('error', reject);
      out.end(() => resolve());
    });
    await rename(tmp, dest);
  } catch (err) {
    await rm(tmp, { force: true });
    throw err;
  }
}

/** The largest PNG thumbnail embedded in a G-code head (`; thumbnail begin WxH len`), or null. */
export async function extractGcodeThumbnail(path: string): Promise<Buffer | null> {
  const { size } = await stat(path);
  const head = (await readRange(path, 0, Math.min(size, 2 * 1024 * 1024))).toString('latin1');
  let best: { area: number; png: Buffer } | null = null;
  // Line scanner (a `[\s\S]*?` block regex is quadratic on many `begin` lines without an `end`).
  let cur: { area: number; parts: string[]; bytes: number } | null = null;
  for (const l of head.split('\n')) {
    const begin = /^;[ \t]*thumbnail begin (\d+)[x*](\d+) (\d+)/.exec(l.length > 200 ? l.slice(0, 200) : l);
    if (begin) {
      cur = { area: Number(begin[1]) * Number(begin[2]), parts: [], bytes: 0 };
      continue;
    }
    if (!cur) continue;
    if (/^;[ \t]*thumbnail end/.test(l)) {
      const png = Buffer.from(cur.parts.join(''), 'base64');
      if (pngSize(png) && (!best || cur.area > best.area)) best = { area: cur.area, png };
      cur = null;
      continue;
    }
    const data = l.replace(/^;[ \t]?/, '').replace(/\s+/g, '');
    cur.bytes += data.length;
    if (cur.bytes > 2 * 1024 * 1024) cur = null; // not a thumbnail
    else cur.parts.push(data);
  }
  return best?.png ?? null;
}
