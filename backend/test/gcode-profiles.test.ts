const FIXTURE = new URL('./fixtures/k2se-cube.gcode', import.meta.url);
const dir = mkdtempSync(join(tmpdir(), 'slicedock-gcode-'));
after(() => rmSync(dir, { recursive: true, force: true }));

describe('G-code summary', () => {
  it('parses the Creality Print 7.3.1 K2 SE footer (real engine output)', async () => {
    assert.deepEqual(await parseGcodeSummary(fileURLToPath(FIXTURE)), {
      printSeconds: 1280,
      filamentGrams: [3.53],
      filamentMm: [1184.13],
      layers: 100,
      printerModel: 'Creality K2 SE',
      slicer: 'Creality_Print V7.3.1.6378',
    });
  });

  it('reads the footer of files bigger than the head window', async () => {
    const text = readFileSync(FIXTURE, 'latin1');
    const at = text.indexOf('; EXECUTABLE_BLOCK_END');
    const padded = text.slice(0, at) + 'G1 X1 Y1\n'.repeat(60_000) + text.slice(at); // ~540 KB
    const p = join(dir, 'padded.gcode');
    writeFileSync(p, padded, 'latin1');
    const s = await parseGcodeSummary(p);
    assert.equal(s.printSeconds, 1280);
    assert.deepEqual(s.filamentGrams, [3.53]);
    assert.equal(s.printerModel, 'Creality K2 SE');
  });

  it('parses an OrcaSlicer-style multi-filament footer', () => {
    const head = '; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.3.1 on 2026-01-01 at 10:00:00\n; total layer number: 250\n; HEADER_BLOCK_END\n';
    const tail = [
      '; filament used [mm] = 1000.50, 200.25',
      '; filament used [g] = 3.01, 0.60',
      '; total filament used [g] = 3.61',
      '; estimated printing time (normal mode) = 1d 2h 3m 4s',
      '; CONFIG_BLOCK_START',
      '; printer_model = Creality K1C',
      '; CONFIG_BLOCK_END',
    ].join('\r\n');
    assert.deepEqual(parseGcodeSummaryText(head, tail), {
      printSeconds: 86400 + 7200 + 180 + 4,
      filamentGrams: [3.01, 0.6],
      filamentMm: [1000.5, 200.25],
      layers: 250,
      printerModel: 'Creality K1C',
      slicer: 'OrcaSlicer 2.3.1',
    });
  });

  it('returns nulls for unknown G-code', () => {
    assert.deepEqual(parseGcodeSummaryText('G28\nG1 X10\n', ''), {
      printSeconds: null,
      filamentGrams: [],
      filamentMm: [],
      layers: null,
      printerModel: null,
      slicer: null,
    });
    assert.equal(parseDuration('21m 20s'), 1280);
    assert.equal(parseDuration('n/a'), null);
  });
});

describe('thumbnail injection', () => {
  it('writes Creality-format PNG blocks after HEADER_BLOCK_END and shifts EXCLUDE_OBJECT_ID offsets', async () => {
    const src = join(dir, 'in.gcode');
    const dest = join(dir, 'out.gcode');
    const original = readFileSync(FIXTURE, 'latin1');
    writeFileSync(src, original, 'latin1');
    const small = makePng(96, 96, [255, 0, 0]);
    const large = makePng(300, 300, [0, 255, 0]);
    await injectThumbnails(src, dest, [
      { width: 96, height: 96, png: small },
      { width: 300, height: 300, png: large },
    ]);
    const out = readFileSync(dest, 'latin1');
    const block = thumbnailBlock([
      { width: 96, height: 96, png: small },
      { width: 300, height: 300, png: large },
    ]);
    assert.ok(out.startsWith('; HEADER_BLOCK_START\n'));
    const at = out.indexOf('; HEADER_BLOCK_END\n\n') + '; HEADER_BLOCK_END\n\n'.length;
    assert.equal(out.slice(at, at + block.length), block);
    assert.match(block, /^; THUMBNAIL_BLOCK_START\n\n;\n; thumbnail begin 96x96 \d+\n; [A-Za-z0-9+/=]{1,78}\n/);
    assert.ok(block.split('\n').every((l) => l.length <= 80));
    // Everything else is unchanged except the byte offsets in the exclude-object footer.
    const before = Number(/END_OFFSET=(\d+)/.exec(original)![1]);
    const afterOff = Number(/END_OFFSET=(\d+)/.exec(out)![1]);
    assert.equal(afterOff, before + Buffer.byteLength(block, 'latin1'));
    assert.equal(out.replace(block, '').replace(/END_OFFSET=\d+/, 'X'), original.replace(/END_OFFSET=\d+/, 'X'));
    // The largest thumbnail round-trips.
    assert.deepEqual(await extractGcodeThumbnail(dest), large);
    assert.equal(await extractGcodeThumbnail(src), null);
  });
});

describe('official profiles (bundled snapshot)', () => {
  const svc = new ProfilesService(() => bundledProfileSource());

  it('lists the K2 SE presets with defaults', () => {
    const b = svc.bundle('creality-k2se');
    assert.equal(b.engineVersion, '7.3.1');
    assert.deepEqual(b.machine.map((m) => m.id), ['Creality K2 SE 0.4 nozzle']);
    assert.equal(b.process.length, 3);
    assert.equal(b.filament.length, 20);
    assert.equal(b.process.find((p) => p.isDefault)?.id, '0.20mm Standard @Creality K2 SE 0.4 nozzle');
    const def = b.filament.find((f) => f.isDefault)!;
    assert.equal(def.id, 'Hyper PLA @Creality K2 SE 0.4 nozzle');
    assert.equal(def.filamentType, 'PLA');
    // Abstract bases are never selectable.
    assert.ok(!b.filament.some((f) => f.id.startsWith('fdm_')));
  });

  it('flattens inherits (parent first, child wins) and drops meta keys', () => {
    const m = svc.resolved('creality-k2se', 'machine', 'Creality K2 SE 0.4 nozzle').values;
    assert.equal(m.gcode_flavor, 'klipper'); // child overrides fdm_creality_common's marlin
    assert.equal(m.printable_area, '0x0,220x0,220x215,0x215');
    assert.equal(m.inherits, undefined);
    assert.equal(m.instantiation, undefined);
    const f = svc.resolved('creality-k2se', 'filament', 'Hyper PLA @Creality K2 SE 0.4 nozzle').values;
    assert.ok(f.filament_density, 'inherited from fdm_filament_pla / common');
    assert.throws(() => svc.resolved('creality-k2se', 'process', 'nope'), /Unknown process preset/);
  });

  it('builds process OptionDefs with Simple/Pro modes from the Creality option table', () => {
    const { options } = svc.bundle('creality-k2se');
    const layer = options.find((o) => o.key === 'layer_height')!;
    assert.deepEqual(layer, {
      key: 'layer_height',
      label: 'Layer height',
      tooltip: 'Slicing height for each layer. Smaller layer height means more accurate and more printing time',
      type: 'float',
      mode: 'simple',
      page: 'Quality',
      group: 'Layer height',
      unit: 'mm',
    });
    const seam = options.find((o) => o.key === 'seam_position')!;
    assert.equal(seam.type, 'enum');
    assert.ok(seam.enumValues!.some((e) => e.value === 'aligned'));
    assert.equal(options.find((o) => o.key === 'wall_generator')?.mode, 'pro');
    assert.ok(options.length > 250);
  });

  it('builds filament OptionDefs (per-slot scalars) without raw G-code templates', () => {
    const { filamentOptions } = svc.bundle('creality-k2se');
    const temp = filamentOptions.find((o) => o.key === 'nozzle_temperature')!;
    assert.equal(temp.type, 'int');
    assert.equal(temp.page, 'Filament');
    assert.equal(filamentOptions.find((o) => o.key === 'enable_pressure_advance')?.type, 'bool');
    assert.ok(!filamentOptions.some((o) => /gcode/.test(o.key)));
    assert.ok(filamentOptions.length > 60);
  });

  it('merges per-slot filament overrides and lists them in different_settings_to_system', () => {
    const scene = {
      version: 1 as const,
      printerModel: 'creality-k2se' as const,
      machinePresetId: 'Creality K2 SE 0.4 nozzle',
      processPresetId: '0.20mm Standard @Creality K2 SE 0.4 nozzle',
      processOverrides: { layer_height: '0.16' },
      filaments: [
        { slot: 2, presetId: 'Hyper PLA @Creality K2 SE 0.4 nozzle', color: '#FFFFFF', overrides: { nozzle_temperature: '235', fan_max_speed: '80' } },
        { slot: 1, presetId: 'Hyper PLA @Creality K2 SE 0.4 nozzle', color: '#000000' },
      ],
      plates: [{ index: 0 }],
      objects: [],
    };
    const cfg = buildProjectConfig(svc, scene);
    const preset = svc.resolved('creality-k2se', 'filament', 'Hyper PLA @Creality K2 SE 0.4 nozzle').values.nozzle_temperature;
    // Slots are sorted: slot 1 is index 0, slot 2 (overridden) index 1.
    assert.deepEqual(cfg.nozzle_temperature, [preset, '235']);
    assert.deepEqual(cfg.different_settings_to_system, ['layer_height', '', 'fan_max_speed;nozzle_temperature', '']);
    assert.throws(
      () => buildProjectConfig(svc, { ...scene, filaments: [{ ...scene.filaments[1]!, overrides: { filament_start_gcode: 'M104 S0' } }] }),
      (e: { code?: string }) => e.code === 'slice.invalid_override',
    );
    assert.throws(
      () => buildProjectConfig(svc, { ...scene, filaments: [{ ...scene.filaments[1]!, overrides: { layer_height: '0.1' } }] }),
      (e: { code?: string }) => e.code === 'slice.invalid_override',
    );
  });
});

describe('option texts in Spanish (Creality Print catalog)', () => {
  const svc = new ProfilesService(() => bundledProfileSource());

  it('translates labels, tooltips, pages, groups and enum labels; keys, values and units stay', () => {
    const es = svc.bundle('creality-k2se', undefined, 'es');
    const layer = es.options.find((o) => o.key === 'layer_height')!;
    assert.equal(layer.label, 'Altura de la capa');
    assert.equal(layer.page, 'Calidad');
    assert.equal(layer.unit, 'mm');
    assert.match(layer.tooltip!, /^Altura de corte para cada capa/);
    const seam = es.options.find((o) => o.key === 'seam_position')!;
    assert.equal(seam.label, 'Posición de la costura');
    assert.deepEqual(seam.enumValues!.find((e) => e.value === 'aligned'), { value: 'aligned', label: 'Alineado' });
    // Filament tab: Creality's page/group names.
    const f = es.filamentOptions!;
    assert.ok(f.some((o) => o.group === 'Información básica'), 'Basic information');
    assert.ok(f.some((o) => o.label === 'Temperatura de ablandado'), 'Softening temperature');
    assert.ok(f.some((o) => o.group === 'Temperatura de la cámara'), 'Print chamber temperature');
    assert.deepEqual([...new Set(f.map((o) => o.page))].slice(0, 3), ['Filamento', 'Refrigeración', 'Anulaciones de configuración']);
    assert.equal(f.find((o) => o.key === 'filament_type')?.label, 'Tipo');
    // English stays English; untranslated strings fall back to English.
    const en = svc.bundle('creality-k2se', undefined, 'en');
    assert.equal(en.options.find((o) => o.key === 'layer_height')!.label, 'Layer height');
    assert.equal(en.filamentOptions!.find((o) => o.key === 'filament_type')?.page, 'Filament');
    assert.equal(es.options.length, en.options.length);
  });
});

describe('engine release picking', () => {
  it('picks the plain x86_64 Release AppImage, never Beta/wayland, highest build', () => {
    const a = (name: string) => ({ name, size: 1, browser_download_url: `https://x/${name}` });
    assert.equal(
      pickAppImage([
        a('CrealityPrint-7.3.1.6378-macx-arm64-Release.dmg'),
        a('CrealityPrint-Linux-flatpak_V7.3.1-Release_x86_64.flatpak'),
        a('CrealityPrint-V7.3.1.6378-x86_64-Release.AppImage'),
        a('CrealityPrint_7.3.1.6378_Release.exe'),
      ])?.name,
      'CrealityPrint-V7.3.1.6378-x86_64-Release.AppImage',
    );
    const picked = pickAppImage([
      a('CrealityPrint-V7.3.0.6149-x86_64-Release.AppImage'),
      a('CrealityPrint-V7.3.0.6157-x86_64-Release.AppImage'),
      a('CrealityPrint-V7.3.0.6151-x86_64-Release.AppImage'),
      a('CrealityPrint-V7.3.0.6160-x86_64-wayland-Beta.AppImage'),
    ]);
    assert.equal(picked?.version, '7.3.0.6157');
    assert.equal(pickAppImage([a('CrealityPrint-V7.2.0-x86_64-Beta-Release.AppImage')]), null);
    assert.ok(compareVersions('7.3.1.6378', '7.3.0.6157') > 0);
    assert.equal(compareVersions('7.3.1', '7.3.1.0'), 0);
  });
});
