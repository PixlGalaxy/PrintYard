describe('engine download integrity (finding #10)', () => {
  const OFFICIAL = 'https://github.com/CrealityOfficial/CrealityPrint/releases/download/v7.3.1/CrealityPrint-V7.3.1.6378-x86_64-Release.AppImage';
  const body = Buffer.from('fake appimage bytes');
  const sha = (b: Buffer) => createHash('sha256').update(b).digest('hex');
  let dir: string;
  before(() => {
    dir = mkdtempSync(join(tmpdir(), 'sd-engine-'));
  });
  after(() => rmSync(dir, { recursive: true, force: true }));

  const stub = (routes: Record<string, () => Response>): typeof fetch =>
    (async (url: string | URL | Request) => {
      const r = routes[String(url)];
      if (!r) throw new Error(`unexpected fetch ${String(url)}`);
      return r();
    }) as typeof fetch;
  const redirect = (to: string) => () => new Response(null, { status: 302, headers: { location: to } });
  const ok = (b: Buffer) => () => new Response(b, { status: 200, headers: { 'content-length': String(b.length) } });

  it('only accepts the official repo and GitHub download hosts', async () => {
    assert.ok(isAllowedAssetUrl(OFFICIAL));
    assert.ok(!isAllowedAssetUrl('https://github.com/evil/CrealityPrint/releases/download/x.AppImage'));
    assert.ok(!isAllowedAssetUrl('http://github.com/CrealityOfficial/CrealityPrint/releases/download/x'));
    assert.equal(sha256FromDigest(`sha256:${'A'.repeat(64)}`), 'a'.repeat(64));
    assert.equal(sha256FromDigest('md5:abc'), null);
    const dest = join(dir, 'a.part');
    await assert.rejects(
      downloadEngineAsset(stub({ [OFFICIAL]: redirect('https://evil.example/x') }), OFFICIAL, dest, { size: body.length, sha256: null }),
      /redirect to evil\.example/,
    );
    await assert.rejects(
      downloadEngineAsset(stub({ [OFFICIAL]: redirect('http://objects.githubusercontent.com/x') }), OFFICIAL, dest, { size: body.length, sha256: null }),
      /redirect/,
    );
    await assert.rejects(downloadEngineAsset(stub({}), 'https://evil.example/a.AppImage', dest, { size: 1, sha256: null }), /Refusing/);
  });

  it('verifies the size and the GitHub sha256 digest', async () => {
    const dest = join(dir, 'b.part');
    const asset = 'https://objects.githubusercontent.com/github-production-release-asset/x';
    const good = await downloadEngineAsset(stub({ [OFFICIAL]: redirect(asset), [asset]: ok(body) }), OFFICIAL, dest, { size: body.length, sha256: sha(body) });
    assert.deepEqual(good, { sha256: sha(body), size: body.length, digestVerified: true });
    await assert.rejects(
      downloadEngineAsset(stub({ [OFFICIAL]: ok(body) }), OFFICIAL, join(dir, 'c.part'), { size: body.length, sha256: 'f'.repeat(64) }),
      /checksum mismatch/,
    );
    await assert.rejects(
      downloadEngineAsset(stub({ [OFFICIAL]: ok(body) }), OFFICIAL, join(dir, 'd.part'), { size: body.length + 5, sha256: null }),
      /size mismatch/,
    );
    assert.deepEqual(readdirSync(dir).sort(), ['b.part']);
  });
});

describe('realtime sessions (finding #11)', () => {
  let t: B1App;
  before(async () => {
    t = await createB1App();
  });
  after(() => t.close());

  it('logout, session revoke, password change and demotion close the sockets; pings do not extend sessions', async () => {
    const live = await startServer(t.ctx);
    try {
      const closed = (c: { ws: import('ws').WebSocket }) => new Promise<number>((r) => c.ws.once('close', (code) => r(code)));
      const origin = live.base;
      // logout → that session's socket closes
      const c1 = await loginCookie(live.base, 'alice', 'alice-password-1');
      const w1 = await wsConnect(live.wsUrl, { Origin: origin, Cookie: c1 });
      await w1.next('hello');
      const w1closed = closed(w1);
      await api(live.base, c1, 'POST', '/api/auth/logout');
      assert.equal(await w1closed, 4401);

      // password change → other sessions' sockets close, the current one stays
      const a = await loginCookie(live.base, 'alice', 'alice-password-1');
      const b = await loginCookie(live.base, 'alice', 'alice-password-1');
      const wa = await wsConnect(live.wsUrl, { Origin: origin, Cookie: a });
      const wb = await wsConnect(live.wsUrl, { Origin: origin, Cookie: b });
      await wa.next('hello');
      await wb.next('hello');
      const wbClosed = closed(wb);
      const pw = await api(live.base, a, 'POST', '/api/account/password', { currentPassword: 'alice-password-1', newPassword: 'alice-password-2' });
      assert.equal(pw.status, 204, JSON.stringify(pw.body));
      assert.equal(await wbClosed, 4401);
      assert.equal(wa.ws.readyState, wa.ws.OPEN);

      // revoking a session from the account page closes its socket
      const c3 = await loginCookie(live.base, 'alice', 'alice-password-2');
      const w3 = await wsConnect(live.wsUrl, { Origin: origin, Cookie: c3 });
      await w3.next('hello');
      const list = (await api(live.base, a, 'GET', '/api/account/sessions')).body.sessions as { id: string; current: boolean }[];
      const other = list.find((s) => !s.current)!;
      const w3closed = closed(w3);
      assert.equal((await api(live.base, a, 'DELETE', `/api/account/sessions/${other.id}`)).status, 204);
      assert.equal(await w3closed, 4401);
      wa.close();

      // role change → disconnected (an ex-admin must not keep admin topics)
      await t.admin.patch(`/api/admin/users/${t.bobId}`).send({ role: 'admin' });
      const bob = await loginCookie(live.base, 'bob', 'bob-password-1');
      const wbob = await wsConnect(live.wsUrl, { Origin: origin, Cookie: bob });
      assert.equal((await wbob.next('hello')).role, 'admin');
      const wbobClosed = closed(wbob);
      await t.admin.patch(`/api/admin/users/${t.bobId}`).send({ role: 'user' });
      assert.equal(await wbobClosed, 4401);

      // WS revalidation does not touch last_seen_at (idle timeout still applies)
      const admin = await loginCookie(live.base, ADMIN.username, ADMIN.password);
      const wad = await wsConnect(live.wsUrl, { Origin: origin, Cookie: admin });
      await wad.next('hello');
      t.ctx.db.prepare('UPDATE sessions SET last_seen_at = 1000').run();
      (t.ctx.hub as unknown as { heartbeat(): void }).heartbeat();
      const seen = t.ctx.db.prepare('SELECT MIN(last_seen_at) AS m FROM sessions').get() as { m: number };
      assert.equal(seen.m, 1000);
      wad.close();
      await waitFor(() => true);
    } finally {
      await live.close();
    }
  });
});

describe('migration 0006 (AUTOINCREMENT rebuild keeps data and foreign keys)', () => {
  it('preserves rows, never reuses referenced ids, restores foreign_keys', () => {
    const src = join(import.meta.dirname, '../src/db/migrations');
    const dir = mkdtempSync(join(tmpdir(), 'sd-mig-'));
    try {
      for (const f of readdirSync(src).filter((n) => n < '0006')) copyFileSync(join(src, f), join(dir, f));
      const db = openDb(':memory:');
      runMigrations(db, dir);
      const now = Date.now();
      db.prepare("INSERT INTO users (id, username, password_hash, role, created_at, updated_at) VALUES (1, 'a', 'x', 'admin', ?, ?)").run(now, now);
      db.prepare("INSERT INTO sessions (id, user_id, created_at, last_seen_at, expires_at) VALUES ('s', 1, ?, ?, ?)").run(now, now, now + 1e6);
      for (const id of [1, 2, 3]) {
        db.prepare("INSERT INTO files (id, owner_id, kind, name, ext, stored_path, size, created_at, updated_at) VALUES (?, 1, 'gcode', 'f', 'gcode', ?, 1, ?, ?)").run(id, `p${id}`, now, now);
      }
      db.prepare("INSERT INTO prints (user_id, printer_id, file_id, file_name, state, created_at) VALUES (1, 1, 3, 'f', 'pending', ?)").run(now);
      db.prepare('DELETE FROM files WHERE id = 3').run();
      runMigrations(db);
      assert.equal(db.pragma('foreign_keys', { simple: true }), 1);
      assert.equal((db.prepare('SELECT COUNT(*) AS n FROM sessions').get() as { n: number }).n, 1);
      assert.equal((db.prepare('SELECT COUNT(*) AS n FROM files').get() as { n: number }).n, 2);
      const id = Number(db.prepare("INSERT INTO files (owner_id, kind, name, ext, stored_path, size, created_at, updated_at) VALUES (1, 'gcode', 'n', 'gcode', 'p9', 1, ?, ?)").run(now, now).lastInsertRowid);
      assert.equal(id, 4, 'id 3 is still referenced by a print, so it is skipped');
      // children still cascade from the rebuilt parent
      db.prepare('DELETE FROM users WHERE id = 1').run();
      assert.equal((db.prepare('SELECT COUNT(*) AS n FROM sessions').get() as { n: number }).n, 0);
      assert.equal((db.prepare('SELECT COUNT(*) AS n FROM files').get() as { n: number }).n, 0);
      db.close();
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
