const GRAMS_PER_MM = (Math.PI * 0.875 ** 2 * 1.24) / 1000; // 1.75 mm PLA

/** G-code that really extrudes `grams` (moves) but may claim something else in a header comment. */
function gcode(opts: { realGrams: number; headerGrams?: number; dwellS?: number; pad?: number }): Buffer {
  const lines = ['; generated by Evil 1.0'];
  if (opts.headerGrams !== undefined) {
    lines.push(`; filament used [g] = ${opts.headerGrams}`, '; estimated printing time (normal mode) = 1m 0s', '; total layers count = 1');
  }
  const mm = opts.realGrams / GRAMS_PER_MM;
  lines.push('G90', 'M83', 'G1 Z0.2 F600', `G1 X10 Y10 E${(mm / 2).toFixed(3)} F3000`, `G1 X20 Y20 E${(mm / 2).toFixed(3)}`);
  if (opts.dwellS) lines.push(`G4 S${opts.dwellS}`);
  if (opts.pad) lines.push(';'.repeat(opts.pad));
  lines.push(`; filament used [g] = ${opts.realGrams}`, '; estimated printing time (normal mode) = 30h 0m 0s', '');
  return Buffer.from(lines.join('\n'));
}

function analyze(text: string, hooks: ((c: GcodeCommand) => void)[] = []) {
  const a = new GcodeAnalyzer({ hooks });
  for (const l of text.split('\n')) a.pushLine(l);
  return a.finish();
}

describe('G-code analyzer (finding #1)', () => {
  it('follows Klipper tokenizing and E modes (G90/G91, M82/M83, G92)', () => {
    assert.deepEqual(parseGcodeLine('N12 g1x10Y-2.5e0.4 ; c', 1)?.params, { X: '10', Y: '-2.5', E: '0.4' });
    assert.equal(parseGcodeLine('N12 g1x10', 1)?.name, 'G1');
    // Extended commands keep the value case like Klipper's _get_extended_params (keys are upper-cased).
    assert.deepEqual(parseGcodeLine('SET_HEATER_TEMPERATURE HEATER=extruder TARGET=300', 2)?.params, { HEATER: 'extruder', TARGET: '300' });
    assert.equal(parseGcodeLine('  ; only a comment', 3), null);
    // absolute E with a G92 reset in the middle: 10 + 5
    assert.equal(analyze('M82\nG1 X1 E10\nG92 E0\nG1 X2 E5').mm[0], 15);
    // relative E (M83), and G91 makes E relative too (Klipper)
    assert.equal(analyze('M83\nG1 X1 E2\nG1 X2 E3').mm[0], 5);
    assert.equal(analyze('M82\nG91\nG1 X1 E2\nG1 X1 E2').mm[0], 4);
    // per tool
    assert.deepEqual(analyze('M83\nT0\nG1 X1 E1\nT1\nG1 X2 E2').mm, [1, 2]);
  });

  it('cannot be gamed with retractions, flow, feedrates or comments', () => {
    // ordinary retract/unretract is not counted twice
    assert.equal(analyze('M83\nG1 X1 E10\nG1 E-1\nG1 E1\nG1 X2 E10').mm[0], 20);
    // a huge "retraction" only earns 20 mm of credit
    assert.equal(analyze('M83\nG1 E-100000\nG1 X1 E1000').mm[0], 980);
    // M221 S1000 makes the printer extrude 10x
    assert.equal(analyze('M83\nM221 S1000\nG1 X1 E10').mm[0], 100);
    // F999999 is capped at the machine maximum (600 mm/s → 6000 mm takes ≥ 10 s)
    assert.ok(analyze('G1 X6000 F999999').seconds >= 10);
    // M220 S10 slows the print down 10x
    assert.ok(analyze('M220 S10\nG1 X100 F6000').seconds >= 10);
    // dwell counts
    assert.ok(analyze('G4 S3600').seconds >= 3600);
    // comments never extrude
    assert.equal(analyze('; G1 X1 E1000\nG1 X1 ; E1000').mm[0], 0);
    // negative comment values are refused by the summary parser
    assert.deepEqual(parseGcodeSummaryText('; filament used [g] = 500,-499', '').filamentGrams, [500]);
  });

  it('hooks see every command (extension point for a dangerous-command scanner)', () => {
    const seen: string[] = [];
    analyze('G28\nSET_KINEMATIC_POSITION Z=0\nM104 S300', [(c) => seen.push(c.name)]);
    assert.deepEqual(seen, ['G28', 'SET_KINEMATIC_POSITION', 'M104']);
    assert.throws(() => analyze('M112', [(c) => {
      if (c.name === 'M112') throw new Error('refused');
    }]), /refused/);
  });
});

