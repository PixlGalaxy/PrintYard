// Crafted G-code must parse in linear time: these inputs made the old whole-text regexes run for seconds to
// minutes on the main thread (any user can upload a G-code; the printer's files are parsed for the ETA).
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, it } from 'node:test';
import { extractGcodeThumbnail, parseGcodeSummaryText } from '../src/modules/files/gcode.js';
import { parseGcodeTiming } from '../src/modules/printing/eta.js';

const MB = 1024 * 1024;
const fill = (unit: string, bytes: number) => unit.repeat(Math.ceil(bytes / unit.length)).slice(0, bytes);
const CASES: Record<string, string> = {
  'many thumbnail begins, no end': fill('; thumbnail begin 32x32 100\n', 2 * MB),
  'generated by + whitespace run': '; generated by x' + ' '.repeat(MB) + 'y\n',
  'estimated printing time without =': ';' + fill('estimated printing time ', MB),
  'semicolon lines': fill(';\n', 2 * MB),
};
const BUDGET_MS = 2000;

describe('G-code parsing stays linear on crafted input', () => {
  for (const [name, text] of Object.entries(CASES)) {
    it(name, async () => {
      const dir = mkdtempSync(join(tmpdir(), 'redos-'));
      try {
        const file = join(dir, 'x.gcode');
        writeFileSync(file, text, 'latin1');
        const t = Date.now();
        parseGcodeSummaryText(text.slice(0, 2 * MB), text.slice(-MB));
        parseGcodeTiming(text.slice(0, MB), text.slice(-256 * 1024), 0);
        await extractGcodeThumbnail(file);
        assert.ok(Date.now() - t < BUDGET_MS, `${name}: ${Date.now() - t} ms`);
      } finally {
        rmSync(dir, { recursive: true, force: true });
      }
    });
  }
});
