import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { after, before, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { GcodeAnalyzer } from '../src/modules/files/gcode-analyzer.js';
import { DEFAULT_SCAN_LIMITS, GcodeScanner, k2seScanLimits, scanGcodeFile } from '../src/modules/files/gcode-scan.js';
import { PrinterSimulator } from '../src/printers/sim/simulator.js';
import type { GcodeScanReason } from '../src/types.js';
import { createB1App, upload, type B1App } from './b1-helpers.js';
import { waitFor } from './live-helpers.js';

const FIXTURE = fileURLToPath(new URL('./fixtures/k2se-cube.gcode', import.meta.url));

function scan(text: string) {
  const s = new GcodeScanner(DEFAULT_SCAN_LIMITS);
  const a = new GcodeAnalyzer({ hooks: [s.hook] });
  for (const l of text.split('\n')) a.pushLine(l);
  return s.result();
}
const reasons = (text: string): GcodeScanReason[] => scan(text).findings.map((f) => f.reason);

const CLEAN = ['; generated by Somebody 1.0', 'G90', 'M83', 'M104 S215', 'M140 S60', 'G1 Z0.2 F600', 'G1 X10 Y10 E1 F3000', 'G1 X20 Y20 E1', ''].join('\n');
const DANGEROUS = ['G90', 'M83', 'G1 X10 Y10 E1 F3000', 'M104 S350', 'SAVE_CONFIG', ''].join('\n');

describe('dangerous-command scanner (finding #3)', () => {
  it('a real Creality Print K2 SE sample passes clean', async () => {
    const r = await scanGcodeFile(FIXTURE, k2seScanLimits());
    assert.equal(r.ok, true, JSON.stringify(r.findings));
    assert.equal(r.total, 0);
  });

  it('derives the temperature maxima from the bundled K2 SE profiles', () => {
    const l = k2seScanLimits();
    assert.equal(l.nozzle, 280); // highest nozzle_temperature_range_high of the K2 SE filaments
    assert.equal(l.bed, 110);
    assert.equal(l.velocity, 800);
    assert.equal(l.accel, 20000);
  });

  it('flags each dangerous category', () => {
    assert.deepEqual(reasons('SAVE_CONFIG\nM500\nM501\nM502\nSAVE_VARIABLE VARIABLE=x VALUE=1'), Array(5).fill('config_write'));
    assert.deepEqual(reasons('RUN_SHELL_COMMAND CMD=rm'), ['shell_command']);
    assert.deepEqual(reasons('FIRMWARE_RESTART\nRESTART'), ['firmware_restart', 'firmware_restart']);
    assert.deepEqual(reasons('M997'), ['firmware_update']);
    assert.deepEqual(reasons('M112'), ['emergency_stop']);
    assert.deepEqual(reasons('SET_KINEMATIC_POSITION Z=0\nSET_STEPPER_ENABLE STEPPER=stepper_z ENABLE=0\nFORCE_MOVE STEPPER=stepper_x DISTANCE=10 VELOCITY=5'), [
      'kinematics',
      'kinematics',
      'kinematics',
    ]);
    // Temperatures above the profile maxima, in every form the K2 SE accepts.
    assert.deepEqual(
      reasons('M104 S301\nM109 S400\nM140 S111\nM190 S120\nM141 S90\nSET_HEATER_TEMPERATURE HEATER=extruder TARGET=350\nSET_HEATER_TEMPERATURE HEATER=heater_bed TARGET=150\nSTART_PRINT EXTRUDER_TEMP=320 BED_TEMP=60'),
      Array(8).fill('temperature_too_high'),
    );
    assert.deepEqual(reasons('M104 S300\nM140 S110\nSET_HEATER_TEMPERATURE HEATER=extruder TARGET=0'), []);
    assert.deepEqual(reasons('SET_HEATER_TEMPERATURE HEATER=my_heater TARGET=50'), ['unknown_heater']);
    assert.deepEqual(reasons('SET_HEATER_TEMPERATURE HEATER=extruder TARGET=inf'), ['invalid_value']);
    assert.deepEqual(reasons('SET_VELOCITY_LIMIT VELOCITY=5000\nM204 S99999'), ['motion_limit', 'motion_limit']);
    // Unknown macros and codes (a macro can do anything on the printer).
    assert.deepEqual(reasons('MY_EVIL_MACRO\nM600\nG29\nSDCARD_PRINT_FILE FILENAME=x'), Array(4).fill('unknown_command'));
  });

  it('cannot be bypassed with Klipper tokenizer tricks', () => {
    assert.deepEqual(reasons('save_config ; lower case'), ['config_write']);
    assert.deepEqual(reasons('SAVE_CONFIG*23'), ['config_write']);
    assert.deepEqual(reasons('N10 FIRMWARE_RESTART'), ['firmware_restart']);
    assert.deepEqual(reasons('m104s350'), ['temperature_too_high']);
    // Commented-out commands are not run by Klipper.
    assert.deepEqual(reasons('; SAVE_CONFIG\nG1 X1 ; M112'), []);
  });

  it('keeps line numbers and caps the stored findings', () => {
    const r = scan(['G90', 'G1 X1', 'M112'].join('\n'));
    assert.deepEqual(r.findings[0], { line: 3, command: 'M112', reason: 'emergency_stop' });
    const many = scan(Array(80).fill('M112').join('\n'));
    assert.equal(many.total, 80);
    assert.equal(many.findings.length, 50);
    assert.equal(many.ok, false);
  });
});

describe('uploaded G-code policy (API, printer simulator)', () => {
  let t: B1App;
  let sim: PrinterSimulator;
  let printerId: number;

  const audit = (action: string) => (t.ctx.audit.list(500) as { action: string; meta?: unknown }[]).filter((e) => e.action === action);
  const pathOf = (id: number) => t.ctx.printFiles.get(id)!.path;
  const markTrusted = (id: number) =>
    t.ctx.db.prepare("UPDATE files SET meta = json_set(meta, '$.trusted', json('true'), '$.gcode.estimateSource', 'slicer') WHERE id = ?").run(id);
  const grant = (id: number, on: boolean) => t.admin.patch(`/api/admin/users/${id}`).send({ canPrintUploadedGcode: on });
  const approval = (requiresApproval: boolean) =>
    t.admin.put(`/api/admin/users/${t.aliceId}/limits`).send({
      enabled: requiresApproval,
      maxGramsPerPrint: null,
      maxGramsPerMonth: null,
      maxHoursPerPrint: null,
      requiresApproval,
    });
  const idle = () =>
    waitFor(() => {
      const s = t.ctx.printerManager.status(printerId);
      return s.online && s.state === 'idle' && s;
    }, 8000);
  const finishOnSim = async () => {
    // Cancel the simulated print once it runs, then clear the bed for the next test.
    await waitFor(() => t.ctx.printerManager.status(printerId).state === 'printing' || !t.ctx.printers.get(printerId).bedClear, 8000);
    if (t.ctx.printers.get(printerId).bedClear) await t.admin.post(`/api/printers/${printerId}/cancel`).send({});
    await waitFor(() => t.ctx.printers.get(printerId).bedClear === false, 8000);
    await t.admin.post(`/api/printers/${printerId}/bed-cleared`).send({});
    await waitFor(() => {
      const s = t.ctx.printerManager.status(printerId);
      return s.online && !['printing', 'paused', 'preparing'].includes(s.state) && t.ctx.printers.get(printerId).bedClear;
    }, 8000);
  };

  before(async () => {
    sim = new PrinterSimulator({ tickMs: 25, simSecondsPerTick: 600, heatPerTick: 100 });
    const port = await sim.start();
    t = await createB1App({
      printerManager: {
        resolveEndpoint: async (host) => (host === 'sim' ? { host: '127.0.0.1', wsPort: port, httpPort: port, moonrakerPort: port } : null),
      },
    });
    printerId = (await t.admin.post('/api/admin/printers').send({ name: 'Sim', model: 'creality-k2se', host: 'sim' })).body.id;
    t.ctx.printerManager.start();
    await idle();
  });
  after(async () => {
    t?.close();
    await sim?.stop();
  });

  it('users list exposes the permission (default off) and only admins can change it (audited)', async () => {
    const list = await t.admin.get('/api/admin/users');
    const alice = list.body.find((u: { id: number }) => u.id === t.aliceId);
    assert.equal(alice.canPrintUploadedGcode, false);
    assert.equal((await t.alice.patch(`/api/admin/users/${t.aliceId}`).send({ canPrintUploadedGcode: true })).status, 403);
    const on = await grant(t.aliceId, true);
    assert.equal(on.body.canPrintUploadedGcode, true);
    assert.ok(audit('user.update').some((e) => JSON.stringify(e).includes('canPrintUploadedGcode')));
    await grant(t.aliceId, false);
  });

  it('without the permission only PrintYard-sliced G-code with a matching sha256 is printable', async () => {
    await approval(true);
    const up = await upload(t.alice, Buffer.from(CLEAN), 'mine.gcode');
    assert.equal(up.status, 201, JSON.stringify(up.body));
    assert.equal(up.body.meta.gcode.scan.ok, true);
    const r = await t.alice.post('/api/prints').send({ printerId, fileId: up.body.id });
    assert.equal(r.status, 403);
    assert.equal(r.body.error.code, 'prints.untrusted_gcode');
    assert.ok(audit('print.refused').some((e) => JSON.stringify(e).includes('prints.untrusted_gcode')));

    // Trusted (sliced) → allowed (pending: alice requires approval).
    const sliced = await upload(t.alice, Buffer.from(CLEAN.replace('S215', 'S210')), 'sliced.gcode');
    markTrusted(sliced.body.id);
    const ok = await t.alice.post('/api/prints').send({ printerId, fileId: sliced.body.id });
    assert.equal(ok.status, 202, JSON.stringify(ok.body));
    await t.alice.delete(`/api/prints/${ok.body.id}`);

    // Trusted flag but the content on disk no longer matches what was sliced → untrusted.
    writeFileSync(pathOf(sliced.body.id), `${CLEAN}M104 S350\n`);
    const tampered = await t.alice.post('/api/prints').send({ printerId, fileId: sliced.body.id });
    assert.equal(tampered.status, 403);
    assert.equal(tampered.body.error.code, 'prints.untrusted_gcode');
  });

  it('with the permission uploads are printable unless the scan finds dangerous commands', async () => {
    await approval(true);
    await grant(t.aliceId, true);
    const clean = await upload(t.alice, Buffer.from(CLEAN.replace('S215', 'S205')), 'clean.gcode');
    const ok = await t.alice.post('/api/prints').send({ printerId, fileId: clean.body.id });
    assert.equal(ok.status, 202, JSON.stringify(ok.body));
    await t.alice.delete(`/api/prints/${ok.body.id}`);

    const bad = await upload(t.alice, Buffer.from(DANGEROUS), 'bad.gcode');
    assert.equal(bad.body.meta.gcode.scan.ok, false);
    const r = await t.alice.post('/api/prints').send({ printerId, fileId: bad.body.id, allowDangerous: true });
    assert.equal(r.status, 403);
    assert.equal(r.body.error.code, 'prints.dangerous_gcode');
    assert.equal(r.body.error.details.total, 2);
    assert.deepEqual(
      r.body.error.details.findings.map((f: { line: number; reason: string }) => [f.line, f.reason]),
      [
        [4, 'temperature_too_high'],
        [5, 'config_write'],
      ],
    );
    assert.equal(audit('print.allow_dangerous').length, 0);
    await grant(t.aliceId, false);
  });

  it('a legacy row without a stored scan is scanned before printing', async () => {
    await grant(t.aliceId, true);
    const bad = await upload(t.alice, Buffer.from(DANGEROUS.replace('S350', 'S351')), 'legacy-bad.gcode');
    t.ctx.db.prepare("UPDATE files SET meta = json_remove(meta, '$.gcode.scan') WHERE id = ?").run(bad.body.id);
    const r = await t.alice.post('/api/prints').send({ printerId, fileId: bad.body.id });
    assert.equal(r.body.error?.code, 'prints.dangerous_gcode');
    const meta = JSON.parse((t.ctx.db.prepare('SELECT meta FROM files WHERE id = ?').get(bad.body.id) as { meta: string }).meta);
    assert.equal(meta.gcode.scan.ok, false); // persisted
    await grant(t.aliceId, false);
  });

  it('approval re-checks the permission and the scan; admins can override (audited)', async () => {
    await approval(true);
    await grant(t.aliceId, true);
    const up = await upload(t.alice, Buffer.from(CLEAN.replace('S215', 'S200')), 'approve-me.gcode');
    const req = await t.alice.post('/api/prints').send({ printerId, fileId: up.body.id });
    assert.equal(req.status, 202);
    // Permission revoked meanwhile → refused, stays pending.
    await grant(t.aliceId, false);
    const denied = await t.admin.post(`/api/prints/${req.body.id}/approve`).send({});
    assert.equal(denied.body.error?.code, 'prints.untrusted_gcode');
    assert.equal((await t.admin.get(`/api/prints/${req.body.id}`)).body.state, 'pending');
    await grant(t.aliceId, true);
    // A stored scan from older rules is not reused: it is re-scanned before approving.
    t.ctx.db.prepare("UPDATE files SET meta = json_set(meta, '$.gcode.scan.version', 0) WHERE id = ?").run(up.body.id);
    const approved = await t.admin.post(`/api/prints/${req.body.id}/approve`).send({});
    assert.equal(approved.status, 200, JSON.stringify(approved.body));
    assert.equal(approved.body.state, 'printing');
    await finishOnSim();
    await grant(t.aliceId, false);
  });

  it('admins: dangerous G-code is refused unless allowDangerous (audited with the findings)', async () => {
    const bad = await upload(t.admin, Buffer.from(DANGEROUS.replace('S350', 'S352')), 'admin-bad.gcode');
    const r = await t.admin.post('/api/prints').send({ printerId, fileId: bad.body.id });
    assert.equal(r.status, 403);
    assert.equal(r.body.error.code, 'prints.dangerous_gcode');
    const forced = await t.admin.post('/api/prints').send({ printerId, fileId: bad.body.id, allowDangerous: true });
    assert.equal(forced.status, 201, JSON.stringify(forced.body));
    const a = audit('print.allow_dangerous');
    assert.equal(a.length, 1);
    assert.ok(JSON.stringify(a[0]).includes('config_write'));
    await finishOnSim();
  });

  it('admins print uploaded clean G-code without any permission flag', async () => {
    const clean = await upload(t.admin, Buffer.from(readFileSync(FIXTURE)), 'creality.gcode');
    assert.equal(clean.body.meta.gcode.scan.ok, true);
    const r = await t.admin.post('/api/prints').send({ printerId, fileId: clean.body.id });
    assert.equal(r.status, 201, JSON.stringify(r.body));
    await finishOnSim();
  });
});
