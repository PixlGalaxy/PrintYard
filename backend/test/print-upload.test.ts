import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import type { PrintableFile } from '../src/modules/printing/files-source.js';
import { PrinterSimulator } from '../src/printers/sim/simulator.js';
import { ADMIN, createTestApp, setupBody, type TestApp } from './helpers.js';
import { api, loginCookie, startServer, waitFor, wsConnect, type LiveServer, type WsClient } from './live-helpers.js';

// ~1.2 MB of G-code so the throttled simulator (600 KiB/s) takes ~2 s: several progress frames.
const GCODE = [
  '; generated by SliceDock test',
  ';LAYER_CHANGE',
  'G1 X10 Y10 E1',
  ...Array.from({ length: 40_000 }, (_, i) => `G1 X${(i % 200) + 1} Y${(i % 150) + 1} E0.01 ; pad`),
  '; estimated printing time (normal mode) = 10m 0s',
  '',
].join('\n');
const GCODE_SHA = createHash('sha256').update(GCODE).digest('hex');

describe('print upload progress (SliceDock → printer)', () => {
  let t: TestApp;
  let live: LiveServer;
  let sim: PrinterSimulator;
  let dir: string;
  let printerId: number;
  let alice: string;
  let adminWs: WsClient;
  let aliceWs: WsClient;
  let bobWs: WsClient;
  const files = new Map<number, PrintableFile>();
  const status = () => t.ctx.printerManager.status(printerId);

  before(async () => {
    dir = mkdtempSync(join(tmpdir(), 'slicedock-upload-'));
    const gpath = join(dir, 'big.gcode');
    writeFileSync(gpath, GCODE);
    sim = new PrinterSimulator({ tickMs: 25, simSecondsPerTick: 600, heatPerTick: 100, uploadBytesPerSec: 600 * 1024 });
    const port = await sim.start();
    t = createTestApp({
      context: {
        printFiles: { get: (id) => files.get(id) ?? null },
        printerManager: {
          resolveEndpoint: async (host) => (host === 'sim' ? { host: '127.0.0.1', wsPort: port, httpPort: port, moonrakerPort: port } : null),
        },
      },
    });
    await t.agent.post('/api/setup/complete').send(setupBody({ printer: null, exposure: { mode: 'none' } }));
    const aliceId = (await t.agent.post('/api/admin/users').send({ username: 'alice', password: 'alice-password-1', role: 'user' })).body.id;
    await t.agent.post('/api/admin/users').send({ username: 'bob', password: 'bob-password-1', role: 'user' });
    const gc = (id: number): PrintableFile => ({
      id, ownerId: aliceId, kind: 'gcode', visibility: 'private', name: `Big ${id}.gcode`, path: gpath, trusted: true, sha256: GCODE_SHA,
      gcode: { printSeconds: 600, filamentGrams: [5], filamentMm: [1600], layers: 1 },
    });
    files.set(1, gc(1));
    files.set(2, gc(2));
    printerId = (await t.agent.post('/api/admin/printers').send({ name: 'Sim', model: 'creality-k2se', host: 'sim' })).body.id;
    t.ctx.printerManager.start();
    live = await startServer(t.ctx);
    const admin = await loginCookie(live.base, ADMIN.username, ADMIN.password);
    alice = await loginCookie(live.base, 'alice', 'alice-password-1');
    const bob = await loginCookie(live.base, 'bob', 'bob-password-1');
    adminWs = await wsConnect(live.wsUrl, { Origin: live.base, Cookie: admin });
    aliceWs = await wsConnect(live.wsUrl, { Origin: live.base, Cookie: alice });
    bobWs = await wsConnect(live.wsUrl, { Origin: live.base, Cookie: bob });
    await waitFor(() => status().state === 'idle', 8000);
  });

  after(async () => {
    adminWs?.close();
    aliceWs?.close();
    bobWs?.close();
    await live?.close();
    t?.close();
    await sim?.stop();
    rmSync(dir, { recursive: true, force: true });
  });

  it('reports state uploading, streams throttled print.upload frames to owner + admins, then printing', async () => {
    const startedAt = Date.now();
    const pending = api(live.base, alice, 'POST', '/api/prints', { printerId, fileId: 1 });
    const uploadingMsg = await aliceWs.next('print.update', (d) => d.state === 'uploading', 5000);
    const printId: number = uploadingMsg.id;
    // While the file is on its way the REST view says uploading too.
    const mid = await api(live.base, alice, 'GET', `/api/prints/${printId}`);
    assert.equal(mid.body.state, 'uploading');
    const res = await pending;
    assert.equal(res.status, 201, JSON.stringify(res.body));
    assert.equal(res.body.state, 'printing');

    const frames = aliceWs.messages.filter((m) => m.type === 'print.upload' && m.data.printId === printId).map((m) => m.data);
    assert.ok(frames.length >= 3, `expected several progress frames, got ${frames.length}`);
    const total = Buffer.byteLength(GCODE);
    for (const f of frames) {
      assert.equal(f.printerId, printerId);
      assert.equal(f.fileName, 'Big 1.gcode');
      assert.equal(f.totalBytes, total);
    }
    for (let i = 1; i < frames.length; i++) assert.ok(frames[i].sentBytes >= frames[i - 1].sentBytes);
    const last = frames.at(-1);
    assert.equal(last.percent, 100);
    assert.equal(last.sentBytes, total);
    assert.equal(last.etaSec, 0);
    assert.ok(frames.slice(0, -1).every((f) => f.percent <= 99), '100 % only once the printer answered');
    // (A 1.2 MB file fits in the loopback socket buffers, so no drain rate/ETA here: see the UploadEstimator test.)
    assert.ok(frames.some((f) => f.percent > 0 && f.percent < 100), 'an intermediate frame');
    // At most 4 frames per second (+ the first and the final one).
    const elapsedSec = (Date.now() - startedAt) / 1000;
    assert.ok(frames.length <= Math.ceil(elapsedSec * 4) + 2, `too many frames: ${frames.length} in ${elapsedSec}s`);

    // Admins get them too, other users do not.
    await waitFor(() => adminWs.messages.some((m) => m.type === 'print.upload' && m.data.printId === printId && m.data.percent === 100));
    assert.ok(!bobWs.messages.some((m) => m.type === 'print.upload'));
    // Order on the owner's socket: uploading → upload frames → printing.
    const seq = aliceWs.messages
      .filter((m) => (m.type === 'print.update' && m.data.id === printId) || (m.type === 'print.upload' && m.data.printId === printId))
      .map((m) => (m.type === 'print.update' ? m.data.state : 'frame'));
    assert.equal(seq[0], 'uploading');
    assert.equal(seq.at(-1), 'printing');
    assert.ok(seq.indexOf('printing') > seq.lastIndexOf('frame'));

    // Free the printer for the next test (which retries while it is still busy).
    await t.agent.post(`/api/printers/${printerId}/cancel`).send({});
  });

  it('a failed upload goes uploading → failed (prints.upload_failed)', async () => {
    sim.failUploads = true;
    sim.uploadBytesPerSec = 0;
    try {
      let res = await api(live.base, alice, 'POST', '/api/prints', { printerId, fileId: 2, confirmBedClear: true });
      for (let i = 0; i < 150 && res.body?.error?.code === 'prints.printer_busy'; i++) {
        await new Promise((r) => setTimeout(r, 100));
        res = await api(live.base, alice, 'POST', '/api/prints', { printerId, fileId: 2, confirmBedClear: true });
      }
      assert.equal(res.status, 502, JSON.stringify(res.body));
      assert.equal(res.body.error.code, 'prints.upload_failed');
      const states = aliceWs.messages.filter((m) => m.type === 'print.update' && m.data.fileName === 'Big 2.gcode').map((m) => m.data.state);
      assert.deepEqual(states, ['uploading', 'failed']);
    } finally {
      sim.failUploads = false;
    }
  });
});

describe('UploadEstimator (socket buffers run ahead of the printer)', () => {
  it('measures the drain rate after the initial burst, keeps percent monotonic and ≤ 99 until done', async () => {
    const { UploadEstimator } = await import('../src/modules/printing/upload-progress.js');
    const MB = 1024 * 1024;
    const e = new UploadEstimator();
    // 10 MB at 1 MB/s through a 6 MB buffer: 6 MB "written" at once, then +2.3 MB steps when the buffer drains.
    assert.deepEqual(e.sample(0, 10 * MB, false, 0), { percent: 0, etaSec: null });
    assert.equal(e.sample(6 * MB, 10 * MB, false, 60).etaSec, null);
    const atBurst = e.sample(6 * MB, 10 * MB, false, 1000); // burst = 6 MB (heartbeat)
    assert.equal(atBurst.percent, 60);
    const step = e.sample(8.3 * MB, 10 * MB, false, 3300); // 2.3 MB more after 2.3 s → ~1 MB/s
    assert.equal(step.percent, 60, 'never goes down while the estimate catches up');
    assert.ok(step.etaSec !== null && step.etaSec >= 6 && step.etaSec <= 8, `eta ${step.etaSec}`);
    const allWritten = e.sample(10 * MB, 10 * MB, false, 5000);
    assert.ok(allWritten.percent >= 60 && allWritten.percent <= 99);
    const later = e.sample(10 * MB, 10 * MB, false, 8000); // still waiting for the printer's answer
    assert.ok(later.percent >= allWritten.percent && later.percent <= 99);
    assert.ok(later.etaSec !== null && later.etaSec <= 3, `eta ${later.etaSec}`);
    assert.deepEqual(e.sample(10 * MB, 10 * MB, true, 10_100), { percent: 100, etaSec: 0 });
  });
});
